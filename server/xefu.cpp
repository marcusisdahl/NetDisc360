const KnownXefu* XefuFor(DWORD titleId) {
    int low=0,high=int(sizeof(Known)/sizeof(Known[0]));
    while(low<high) {
        int middle=(low+high)/2;
        if(Known[middle].titleId<titleId) low=middle+1;
        else high=middle;
    }
    return low<int(sizeof(Known)/sizeof(Known[0])) && Known[low].titleId==titleId ? &Known[low] : NULL;
}

bool XefuName(const std::string& name) {
    size_t start=!name.compare(0,4,"xefu") ? 4 : !name.compare(0,18,"config_loader_xefu") ? 18 : 0;
    if(!start || name.size()>start+24 || !name.compare(0,9,"xefutitle")) return false;
    for(size_t i=start;i<name.size();++i) if(!isalnum((unsigned char)name[i]) && name[i]!='_') return false;
    return true;
}
