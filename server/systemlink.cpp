const SystemLinkGame* FindSystemLink(DWORD titleId) {
    size_t low=0, high=SystemLinkCount;
    while(low<high) {
        size_t middle=(low+high)/2;
        if(SystemLinkGames[middle].titleId<titleId) low=middle+1;
        else high=middle;
    }
    return low<SystemLinkCount && SystemLinkGames[low].titleId==titleId ? &SystemLinkGames[low] : NULL;
}
