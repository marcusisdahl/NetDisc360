"""Makes third_party/lucide/lucide_icons.h, the icons of NetDisc 360's window.

Subsets Lucide's icon font (npm package lucide-static, font/lucide.ttf and
font/codepoints.json) to the icons in ICONS and writes it as a byte array,
with one #define per icon (its UTF-8 text). Needs fontTools.

    python tools/make_icons.py <lucide-static>/font/lucide.ttf <lucide-static>/font/codepoints.json
"""
import io
import json
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

VERSION = "1.49.0"  # lucide-static
# C name: Lucide name.
ICONS = {
    "Games": "gamepad-2",
    "Folder": "folder",
    "FolderPlus": "folder-plus",
    "FolderOpen": "folder-open",
    "Xbox": "monitor",
    "Log": "scroll-text",
    "Settings": "settings",
    "Info": "info",
    "ChevronRight": "chevron-right",
    "Search": "search",
    "Plus": "plus",
    "Refresh": "rotate-cw",
    "Grid": "layout-grid",
    "List": "list",
    "Tag": "tag",
    "Image": "image",
    "Close": "x",
    "Check": "check",
    "Box": "square",
    "BoxChecked": "square-check",
    "Radio": "circle",
    "RadioOn": "circle-dot",
    "Link": "external-link",
    "Copy": "copy",
    "Eye": "eye",
    "EyeOff": "eye-off",
    "Warning": "triangle-alert",
    "Play": "play",
    "Power": "power",
    "Disc": "disc-3",
    "SortName": "arrow-down-a-z",
    "SortSize": "arrow-down-wide-narrow",
    "Network": "network",
    "Heart": "heart",
    "Quit": "log-out",
    "Remove": "trash-2",
    "Ok": "circle-check",
    "Failed": "circle-x",
    "Spinner": "loader-circle",
    "Wifi": "wifi",
    "Cable": "cable",
    "Drive": "hard-drive",
    "Github": "github",
    "Palette": "palette",
    "Windows": "app-window",
    "Sliders": "sliders-horizontal",
    "Key": "key-round",
}


def main():
    font_path, codepoints_path = sys.argv[1:3]
    codepoints = json.load(open(codepoints_path))
    missing = [name for name in ICONS.values() if name not in codepoints]
    if missing:
        sys.exit("Not in this Lucide: " + ", ".join(missing))
    font = TTFont(font_path)
    options = subset.Options()
    options.layout_features = []
    options.hinting = False
    options.desubroutinize = True
    options.name_IDs = []
    options.notdef_outline = True
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[codepoints[name] for name in ICONS.values()])
    subsetter.subset(font)
    data = io.BytesIO()
    font.save(data)
    data = data.getvalue()

    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    out = os.path.join(root, "third_party", "lucide", "lucide_icons.h")
    lines = [
        "// Lucide icons %s (ISC License, see LICENSE), subset to the icons of" % VERSION,
        "// NetDisc 360's window. Generated by tools/make_icons.py; don't edit.",
        "#pragma once",
        "",
    ]
    width = max(len(c) for c in ICONS)
    for c_name, name in ICONS.items():
        utf8 = chr(codepoints[name]).encode("utf-8")
        text = "".join("\\x%02x" % b for b in utf8)
        lines.append('#define ICON_%s "%s"  // %s' % (c_name.ljust(width), text, name))
    lines.append("")
    lines.append("// Every icon's code point lies in this range.")
    points = [codepoints[name] for name in ICONS.values()]
    lines.append("#define ICON_FIRST 0x%04X" % min(points))
    lines.append("#define ICON_LAST 0x%04X" % max(points))
    lines.append("")
    lines.append("static const unsigned char LucideIcons[%d] = {" % len(data))
    for i in range(0, len(data), 20):
        lines.append("    " + ",".join("0x%02x" % b for b in data[i:i + 20]) + ",")
    lines.append("};")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("Wrote %s (%d icons, %d bytes of font)" % (out, len(ICONS), len(data)))


if __name__ == "__main__":
    main()
